fun resolveAuraStrings(selectedLanguageCode: String): AuraStrings {
  val effectiveCode =
    if (selectedLanguageCode.equals("SYSTEM", ignoreCase = true) || selectedLanguageCode.isBlank()) {
      val locale = Locale.getDefault()
      val lang = locale.language.lowercase(Locale.ROOT)
      val country = locale.country.uppercase(Locale.ROOT)
      val script = locale.script.lowercase(Locale.ROOT)
      when {
        lang == "zh" && (country in setOf("TW", "HK", "MO") || script == "hant") -> "zh-TW"
        lang == "zh" -> "zh-CN"
        lang == "ja" -> "ja"
        lang == "ko" -> "ko"
        lang == "es" -> "es"
        lang == "de" -> "de"
        else -> "en"
      }
    } else {
      selectedLanguageCode
    }

  return when (effectiveCode.lowercase(Locale.ROOT)) {
    "zh-cn", "zh_cn", "zh-hans" -> SimplifiedChineseAuraStrings
    "zh-tw", "zh_tw", "zh-hk", "zh_hk", "zh-hant" -> TraditionalChineseAuraStrings
    "ja", "ja-jp" -> JapaneseAuraStrings
    "ko", "ko-kr" -> KoreanAuraStrings
    "es", "es-es" -> SpanishAuraStrings
    "de", "de-de" -> GermanAuraStrings
    else -> EnglishAuraStrings
  }
}

